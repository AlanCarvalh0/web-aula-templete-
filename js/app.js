function renderizarNoticias() {
    const lista = document.getElementById("lista-noticias");

    if (!lista) {
        return; 
    }

    lista.innerHTML = "";

        dados.forEach(function(noticia) {
        const cartao = document.createElement("article");
        cartao.classList.add("cartao");

        cartao.innerHTML = `
            <img src="${noticia.imagem}" alt="${noticia.titulo}">
            <h2>${noticia.titulo}</h2>
            <div class="informacoes">
                <span class="categoria">${noticia.categoria}</span>
                <span class="data">${noticia.data}</span>
            </div>
            <p class="descricao">${noticia.descricao}</p>
            <p class="autor">${noticia.autor}</p>
            <a class="btn-leia-mais" href="detalhes.html?id=${noticia.id}">Leia mais</a>
        `;

        lista.appendChild(cartao);
    });
}

renderizarNoticias();


function mostrarDetalhes() {
    const area = document.getElementById("detalhe-noticia");

    if (!area) {
        return; 
    }

    const parametros = new URLSearchParams(window.location.search);
    const idNoticia = Number(parametros.get("id"));

    const noticia = dados.find(function(item) {
        return item.id === idNoticia;
    });

    if (!noticia) {
        area.innerHTML = "<p>Notícia não encontrada.</p>";
        return;
    }

    area.innerHTML = `
       <article class="cartao cartao-detalhe">
            <img src="${noticia.imagem}" alt="${noticia.titulo}">
            <h2>${noticia.titulo}</h2>
            <div class="informacoes">
                <span class="categoria">${noticia.categoria}</span>
                <span class="data">${noticia.data}</span>
            </div>
            <p class="autor">Por: ${noticia.autor}</p>
            <p class="descricao">${noticia.conteudo}</p>
        </article>
    `;
}

mostrarDetalhes();

function configurarMenu() {
    const botaoMenu = document.querySelector(".menu");
    const menuLateral = document.querySelector(".lateral");

    if (!botaoMenu || !menuLateral) {
        return;
    }

    botaoMenu.addEventListener("click", function() {
        menuLateral.classList.toggle("ativo");
        const ativo = menuLateral.classList.contains("ativo");
        botaoMenu.setAttribute("aria-expanded", String(ativo));
    });
}

configurarMenu();